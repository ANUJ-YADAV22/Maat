import { motion } from 'framer-motion'
import { Gauge, ScrollText } from 'lucide-react'
import type { Explain, GateRun, Passport } from '../types'
import { CardHead, Meter, fmt } from './ui'

export function PassportCard({ p }: { p: Passport }) {
  const tone = p.status === 'adopted' ? 'var(--gold)' : p.status === 'rejected' ? 'var(--bad)' : p.status === 'rolled_back' ? 'var(--gold)' : 'var(--warn)'
  return (
    <motion.div className={`passport ${p.status}`} initial={{ opacity: 0, rotateX: -8, y: 12 }} animate={{ opacity: 1, rotateX: 0, y: 0 }} transition={{ duration: 0.6 }}>
      <div className="stamp" style={{ color: tone }}>{p.status.replace('_', ' ')}</div>
      <div className="tag">Patch Passport · {p.patch_id}</div>
      <div className="title" style={{ marginTop: 6 }}>{p.claim}</div>
      <div className="fields">
        <div><b>Evidence</b>{p.evidence}</div>
        <div><b>Rule</b>{p.rule}</div>
        <div><b>Method</b>{p.method}</div>
        <div><b>Generated by</b>{p.generated_by}</div>
        <div><b>Result</b><span style={{ color: tone, fontWeight: 700 }}>{p.result}</span></div>
        <div><b>Next action</b>{p.next_action}</div>
      </div>
      <div className="foot">{p.note}</div>
    </motion.div>
  )
}

export function ExplainBlock({ e }: { e: Explain }) {
  return (
    <div>
      <CardHead title="Why" icon={<ScrollText size={16} color="var(--gold)" />} />
      <div className="display" style={{ fontSize: 19, lineHeight: 1.3, marginBottom: 10 }}>{e.headline}</div>
      <div className="col" style={{ gap: 6 }}>
        {e.lines.map((l, i) => <div key={i} className="muted" style={{ fontSize: 13 }}>• {l}</div>)}
      </div>
    </div>
  )
}

export function DecisionMetrics({ runs }: { runs: GateRun[] }) {
  const dec = runs.find((r) => r.lock === 'decision')?.metrics_json
  const imp = runs.find((r) => r.lock === 'impact')?.metrics_json
  if (!dec || dec.score === undefined) return null
  const max = Math.max(0.2, dec.gain_lcb, dec.bar * 2, dec.score)
  return (
    <div>
      <CardHead title="Evidence vs risk" icon={<Gauge size={16} color="var(--gold)" />} />
      <div className="grid g2" style={{ gap: 18 }}>
        <div>
          <div className="row" style={{ justifyContent: 'space-between', marginBottom: 6 }}><span className="muted">Score = gain LCB − λ · harm UCB</span><b className="mono">{fmt(dec.score)}</b></div>
          <Meter value={Math.max(0, dec.score)} max={max} mark={dec.bar} color={dec.score >= dec.bar ? 'linear-gradient(90deg,#1f9d6b,#3fdc9a)' : 'linear-gradient(90deg,#b8404f,#ff6173)'} />
          <div className="faint" style={{ fontSize: 12, marginTop: 8 }}>Bar {fmt(dec.bar)} · tier {dec.tier} · λ {dec.lambda} · trust {fmt(dec.e_trust, 2)}</div>
        </div>
        <dl className="kv" style={{ gridTemplateColumns: '120px 1fr' }}>
          <dt>Gain (LCB)</dt><dd className="mono">{fmt(dec.gain_lcb)}</dd>
          <dt>Harm (UCB)</dt><dd className="mono">{fmt(dec.harm_ucb)}</dd>
          <dt>Margin</dt><dd className="mono">{fmt(dec.margin)}</dd>
          <dt>Replays</dt><dd className="mono">{dec.replays ?? '—'} <span className="faint">({dec.gate_seconds}s)</span></dd>
        </dl>
      </div>
      {imp && imp.scope_precision !== undefined && (
        <>
          <div className="divider" />
          <div className="grid g4">
            {[['Scope precision', imp.scope_precision], ['Scope recall', imp.scope_recall], ['Coverage', imp.coverage], ['Noise floor', imp.noise_floor_mean]].map(([l, v]) => (
              <div key={l as string}><div className="faint" style={{ fontSize: 11, letterSpacing: '.1em', textTransform: 'uppercase' }}>{l as string}</div><div className="display" style={{ fontSize: 26 }}>{fmt(v as number, 2)}</div></div>
            ))}
          </div>
          {imp.changed_out_of_scope?.length > 0 && (
            <div className="bubble" style={{ marginTop: 12, borderColor: 'rgba(255,97,115,.35)' }}>
              <b style={{ color: 'var(--bad)' }}>Undeclared impact</b>
              {imp.changed_out_of_scope.slice(0, 4).map((c: { id: string; family: string; input: string }) => (
                <div key={c.id} className="muted mono" style={{ fontSize: 12, marginTop: 4 }}>{c.family}: {c.input}</div>
              ))}
            </div>
          )}
        </>
      )}
    </div>
  )
}
